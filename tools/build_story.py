PL_MAP = {
    "Ą": 96, "Ć": 97, "Ę": 98, "Ł": 99, "Ń": 100,
    "Ó": 101, "Ś": 102, "Ź": 103, "Ż": 104,
}

def encode_str(s):
    out = bytearray()
    for ch in s.upper():
        if ch in PL_MAP:
            out.append(PL_MAP[ch])
        else:
            code = ord(ch)
            out.append(code if 32 <= code <= 95 else 32)
    out.append(0)
    return bytes(out)

