def compile_lang(idx, out_path):
    strs = [pair[idx] for pair in ENTRIES]
    for i, s in enumerate(strs):
        if len(s) > 40:
            raise ValueError(f"Tekst ID={i} za dlugi ({len(s)} > 40): {s}")
    encoded = [encode_str(s) for s in strs]
    count = len(encoded)
    hdr_sz = 8 + count * 2
    offsets = list()
    cur = hdr_sz
    for b in encoded:
        offsets.append(cur)
        cur += len(b)
    blob = bytearray(struct.pack(">4sHH", b"AFST", count, cur))
    for off in offsets:
        blob.extend(struct.pack(">H", off))
    for b in encoded:
        blob.extend(b)
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    open(out_path, "wb").write(blob)
    print(f"OK: {out_path} ({count} wpisow, {len(blob)} B)")

